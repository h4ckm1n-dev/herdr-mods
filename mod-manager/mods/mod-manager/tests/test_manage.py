import importlib.util
import json
from pathlib import Path
import tempfile
import subprocess
import sys
import unittest
from unittest.mock import patch

SPEC = importlib.util.spec_from_file_location("manage", Path(__file__).parents[1] / "manage.py")
manage = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(manage)
CAT = [{"id": "agents-crew", "desc": "Agents", "fallback": "agents"}, {"id": "cost", "desc": "Cost"}]


class SwitchTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.home = Path(self.temp.name)
        (self.home / "disabled-mods").mkdir()
        for name in ("agents-crew", "agents", "cost"):
            folder = self.home / "mods" / name
            folder.mkdir(parents=True)
            (folder / "main.js").write_text(name)
            (folder / "mod.json").write_text("{}")

    def test_fallback_and_exact_restore(self):
        folder = self.home / "mods/agents-crew"
        original = manage.digest(folder)
        manage.toggle(self.home, CAT, "agents-crew", False)
        self.assertEqual((folder / "main.js").read_text(), "agents")
        self.assertFalse(manage.listing(self.home, CAT)[0]["on"])
        manage.toggle(self.home, CAT, "agents-crew", False)
        (folder / "gpui-kit.d.ts").write_text("generated by Herdr")
        manage.toggle(self.home, CAT, "agents-crew", True)
        self.assertEqual(manage.digest(folder), original)

    def test_placeholder_never_loads_original(self):
        manage.toggle(self.home, CAT, "cost", False)
        text = (self.home / "mods/cost/main.js").read_text()
        self.assertIn("class Disabled", text)
        self.assertNotIn('import "./', text)
        manage.toggle(self.home, CAT, "cost", True)
        self.assertEqual((self.home / "mods/cost/main.js").read_text(), "cost")

    def test_edits_and_reinstall_are_preserved(self):
        manage.toggle(self.home, CAT, "cost", False)
        folder = self.home / "mods/cost"
        (folder / "main.js").write_text("user edit")
        with self.assertRaises(ValueError):
            manage.toggle(self.home, CAT, "cost", True)
        self.assertEqual((folder / "main.js").read_text(), "user edit")
        self.assertEqual((self.home / "disabled-mods/cost/main.js").read_text(), "cost")
        (folder / manage.MARK).unlink()
        with self.assertRaises(ValueError):
            manage.toggle(self.home, CAT, "cost", False)

    def test_kept_files_stay_runnable_while_off(self):
        cat = CAT + [{"id": "claude-usage", "desc": "Quotas", "keep": ["statusline.py"]}]
        folder = self.home / "mods/claude-usage"
        folder.mkdir()
        (folder / "main.js").write_text("usage")
        (folder / "statusline.py").write_text("print('wrapped')")
        manage.toggle(self.home, cat, "claude-usage", False)
        self.assertIn("class Disabled", (folder / "main.js").read_text())
        out = subprocess.run([sys.executable, "-I", str(folder / "statusline.py")], capture_output=True, text=True)
        self.assertEqual(out.stdout.strip(), "wrapped")  # Claude Code's statusline keeps working
        manage.toggle(self.home, cat, "claude-usage", True)
        self.assertEqual((folder / "main.js").read_text(), "usage")
        self.assertFalse((folder / manage.MARK).exists())

    def test_failed_swap_restores_original(self):
        rename = Path.rename

        def fail_stage(path, target):
            if path.name == "replacement":
                raise OSError("simulated swap failure")
            return rename(path, target)

        with patch.object(Path, "rename", fail_stage), self.assertRaises(OSError):
            manage.toggle(self.home, CAT, "cost", False)
        self.assertEqual((self.home / "mods/cost/main.js").read_text(), "cost")
        self.assertFalse((self.home / "disabled-mods/cost").exists())

    def test_rejects_unknown_names_and_symlinks(self):
        for name in ("../agents", "agents", "mod-manager"):
            with self.assertRaises(ValueError):
                manage.toggle(self.home, CAT, name, False)
        (self.home / "mods/cost/link").symlink_to(self.home / "mods/agents")
        with self.assertRaises(ValueError):
            manage.toggle(self.home, CAT, "cost", False)

    def test_recover_interrupted_swap(self):
        (self.home / "mods/cost").rename(self.home / "disabled-mods/cost")
        manage.toggle(self.home, CAT, "cost", True)
        self.assertEqual((self.home / "mods/cost/main.js").read_text(), "cost")

    def test_catalog_covers_installer(self):
        root = Path(__file__).resolve().parents[4]
        catalog = json.loads(Path(__file__).parents[1].joinpath("catalog.json").read_text())
        names = {e["id"] for e in catalog}
        listed = {line.split("\t")[0] for line in (root / "mods.tsv").read_text().splitlines() if line and not line.startswith("#")}
        self.assertTrue(listed <= names)
        self.assertEqual(len(names), len(catalog))

    def test_installer_skips_a_disabled_mod(self):
        root = Path(__file__).resolve().parents[4]
        manage.toggle(self.home, CAT, "cost", False)
        before = manage.digest(self.home / "mods/cost")
        result = subprocess.run([sys.executable, "-I", "install.py", str(self.home), "cost"],
                                cwd=root, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)  # skipped with a word, the rest still installs
        self.assertIn("skipped, disabled in OhMyHerdr Mods", result.stdout)
        self.assertEqual(manage.digest(self.home / "mods/cost"), before)


if __name__ == "__main__":
    unittest.main()
